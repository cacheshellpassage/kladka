/**
 * `pnpm content:build` — runs all generators and writes the core content pack to
 * apps/app/public/packs/core (pack.json + builds/*.kbuild). Existing preview entries are preserved.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import type { ContentPackManifest } from "@kladka/voxel-core";
import { CATALOG, buildOne, packManifest } from "./pack";

const here = dirname(fileURLToPath(import.meta.url));
export const PACK_DIR = resolve(here, "../../../apps/app/public/packs/core");

function main(): void {
  mkdirSync(join(PACK_DIR, "builds"), { recursive: true });
  const manifestPath = join(PACK_DIR, "pack.json");
  const previous: ContentPackManifest | null = existsSync(manifestPath)
    ? (JSON.parse(readFileSync(manifestPath, "utf8")) as ContentPackManifest)
    : null;
  const entries = [];
  let totalBytes = 0;
  for (const e of CATALOG) {
    const t = Date.now();
    const { entry, bytes } = buildOne(e);
    const prev = previous?.builds.find((b) => b.id === e.id);
    if (prev?.previews) entry.previews = prev.previews;
    writeFileSync(join(PACK_DIR, entry.file), bytes);
    totalBytes += bytes.length;
    entries.push(entry);
    const s = entry.stats!;
    console.log(
      `${e.id.padEnd(20)} ${s.size.join("×").padEnd(10)} ${String(s.blocks).padStart(5)} blocks ${String(s.steps).padStart(4)} steps  d${s.difficulty}  ${Date.now() - t} ms`,
    );
  }
  writeFileSync(manifestPath, JSON.stringify(packManifest(entries), null, 2) + "\n");
  writeFileSync(
    join(PACK_DIR, "LICENSE.txt"),
    "Kladka core content pack\n\nAll builds and preview images in this folder were generated by the Kladka project's own\n" +
      "generators and are dedicated to the public domain under CC0 1.0 Universal:\n" +
      "https://creativecommons.org/publicdomain/zero/1.0/\n\n" +
      "NOT AN OFFICIAL MINECRAFT PRODUCT. NOT APPROVED BY OR ASSOCIATED WITH MOJANG OR MICROSOFT.\n",
  );
  console.log(`\n${entries.length} builds, ${(totalBytes / 1024).toFixed(1)} KiB → ${PACK_DIR}`);
}

main();
